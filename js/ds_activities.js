function runFeatureRecode() {
    const cutoffEl = document.getElementById('recodeCutoff');
    const imputeEl = document.getElementById('imputeStrategy');
    if (!cutoffEl || !imputeEl) return;

    const cutoff = parseInt(cutoffEl.value);
    const impute = imputeEl.value;
    const statsOut = document.getElementById('recodeStatsOutput');
    const codeOut = document.getElementById('recodeCodeSnippet');

    let processed = sampleSurveyData.map(d => ({ ...d }));

    if (impute === 'drop') {
        processed = processed.filter(d => d.ai_risk !== -9);
    } else if (impute === 'median') {
        processed = processed.map(d => ({ ...d, ai_risk: d.ai_risk === -9 ? 3 : d.ai_risk }));
    }

    // Rows still carrying the -9 missing code must be excluded from BOTH the
    // flag count and the weighted mean. Including them dragged the mean far
    // below the true value and contradicted the Python snippet shown below.
    const valid = processed.filter(d => d.ai_risk !== -9 && d.ai_risk !== null);
    const nMissing = processed.length - valid.length;

    const highRiskCount = valid.filter(d => d.ai_risk >= cutoff).length;
    const pct = valid.length ? Math.round((highRiskCount / valid.length) * 100) : 0;

    const totalWeight = valid.reduce((sum, d) => sum + d.weight, 0);
    const weightedRiskSum = valid.reduce((sum, d) => sum + (d.ai_risk * d.weight), 0);
    const weightedAvgRisk = totalWeight ? (weightedRiskSum / totalWeight).toFixed(2) : 'n/a';

    if (statsOut) {
        statsOut.innerHTML = `
            • Total Sample Rows Processed: <strong>${processed.length}</strong><br>
            • Excluded as missing (-9): <strong>${nMissing}</strong> → <strong>${valid.length}</strong> valid<br>
            • High Risk Flag Threshold: <strong>Perceived AI Risk >= ${cutoff}</strong><br>
            • High Risk Count: <strong>${highRiskCount} of ${valid.length} valid (${pct}%)</strong><br>
            • Population Weighted Mean Risk Score: <strong>${weightedAvgRisk} / 5.0</strong>
            <span style="color:var(--text-muted);">(missing excluded, as SAS does with <code>.</code>)</span>
        `;
    }

    if (codeOut) {
        codeOut.innerText = `# Python Pandas Equivalent Code:
df['AI_Risk_Clean'] = df['Perceived_AI_Risk'].replace(-9, ${impute === 'median' ? 'df["Perceived_AI_Risk"].median()' : 'None'})
df['High_Risk_Flag'] = (df['AI_Risk_Clean'] >= ${cutoff}).astype(int)
weighted_mean = (df['AI_Risk_Clean'] * df['Survey_Weight']).sum() / df['Survey_Weight'].sum()`;
    }
}

