function runHypothesisTest() {
    const rowVarEl = document.getElementById('hypoRowVar');
    const colVarEl = document.getElementById('hypoColVar');
    const out = document.getElementById('hypoResultsOutput');

    if (!rowVarEl || !colVarEl || !out) return;

    const rowVar = rowVarEl.value;
    const colVar = colVarEl.value;

    out.innerHTML = 'Loading the full 1,200-row dataset…';

    loadSurveyData().then(function (rows) {
        const ct = crosstabChiSquare(rows, rowVar, colVar);
        const ors = oddsRatios(ct, 1);           // positive outcome = High_AI_Trust == 1
        const sig = ct.pValue < 0.05;

        // DATASET.signal records which predictors truly drive the outcome, so the
        // app can tell the learner whether their result matches ground truth.
        const isNoise = (typeof DATASET !== 'undefined') &&
                        DATASET.signal.noise.indexOf(rowVar) !== -1;

        const rowsHtml = ors.map(function (o) {
            return '• ' + o.level + ': ' + o.pct.toFixed(1) + '% High Trust ' +
                   '(n=' + o.n + ', OR ' +
                   (o.isReference ? '1.00 — reference' : o.oddsRatio.toFixed(2)) + ')';
        }).join('<br>');

        const verdict = sig
            ? '<span style="color:#4ADE80;">Statistically significant (p &lt; 0.05)</span>'
            : '<span style="color:#FBBF24;">Not statistically significant</span>';

        const truth = isNoise
            ? '<div style="margin-top:12px;padding:12px;background:rgba(251,191,36,0.1);' +
              'border-left:3px solid #FBBF24;border-radius:6px;color:var(--text-main);">' +
              '<strong>Ground truth:</strong> <code>' + rowVar + '</code> is <strong>pure noise</strong> ' +
              'in this dataset — it plays no part in the equation that generates trust ' +
              '(see <code>scripts/setup_ai_trust_data.py</code>). Finding no significant ' +
              'effect here is the <em>correct</em> result. Reporting a null finding with ' +
              'confidence is a real skill.</div>'
            : '<div style="margin-top:12px;padding:12px;background:rgba(74,222,128,0.1);' +
              'border-left:3px solid #4ADE80;border-radius:6px;color:var(--text-main);">' +
              '<strong>Ground truth:</strong> <code>' + rowVar + '</code> <strong>is</strong> ' +
              'one of the variables that genuinely drives trust in the generating equation. ' +
              'You just recovered a real effect from the data.</div>';

        const warn = ct.minExpected < 5
            ? '<br><em style="color:#FBBF24;">⚠️ Smallest expected cell count is ' +
              ct.minExpected.toFixed(1) + ' (&lt; 5) — chi-square may be unreliable here.</em>'
            : '';

        out.innerHTML =
            '<strong>Crosstab: ' + rowVar + ' × ' + colVar + '</strong> ' +
            '<span style="color:var(--text-muted);">(computed live, n = ' + ct.n + ')</span><br>' +
            rowsHtml + '<br><br>' +
            '<strong>Pearson Chi-Square:</strong> χ² = ' + ct.chi2.toFixed(2) +
            ' (df = ' + ct.df + ')<br>' +
            '<strong>p-value:</strong> ' + formatPValue(ct.pValue) + ' — ' + verdict + warn +
            '<br><br><em>SAS equivalent: PROC FREQ data=survey; tables ' +
            rowVar + '*' + colVar + ' / chisq relrisk; run;</em>' +
            truth;
    }).catch(function (err) {
        out.innerHTML =
            '<span style="color:#EF4444;">Could not load ' + SURVEY_CSV_PATH + ' — ' +
            err.message + '.<br>These statistics are computed from the real CSV, so they ' +
            'cannot be shown without it. Serve the app over HTTP ' +
            '(<code>python -m http.server 8000</code>) rather than opening the file directly.</span>';
    });
}

