// ── Renderers ─────────────────────────────────────────────────────────────────

function renderDatasetProvenance(containerId) {
    const el = document.getElementById(containerId);
    if (!el) return;
    const o = DATASET.origin;
    el.innerHTML =
        '<strong>What dataset is this?</strong> ' + o.statement +
        ' There are <strong>' + DATASET.rows.toLocaleString() + ' rows</strong>, each representing ' +
        '<strong>' + DATASET.unitOfAnalysis + '</strong>.' +
        '<div style="margin-top:12px;padding-top:12px;border-top:1px solid rgba(255,255,255,0.12);">' +
            '<strong style="color:var(--gold-primary);">Why synthetic data is better here:</strong> ' +
            o.whyThisMatters +
        '</div>' +
        '<div style="margin-top:10px;font-size:0.85rem;color:var(--text-muted);">' +
            'Generator: <code>' + o.generatorScript + '</code> (seed ' + o.seed + ') · ' +
            'Structure inspired by <a href="' + o.inspiredBy.url + '" target="_blank" rel="noopener" ' +
            'style="color:var(--cyan-magic);">' + o.inspiredBy.title + '</a> by ' +
            o.inspiredBy.author + ' (' + o.inspiredBy.license + ')' +
        '</div>';
}

function renderDataDictionary(containerId) {
    const el = document.getElementById(containerId);
    if (!el) return;
    const rows = DATASET.columns.map(function (c) {
        return '<tr style="border-bottom:1px solid rgba(255,255,255,0.08);">' +
            '<td style="padding:10px;font-family:var(--font-mono);color:#38BDF8;">' + c.name + '</td>' +
            '<td style="padding:10px;">' + c.type + '</td>' +
            '<td style="padding:10px;">' + c.values + '</td>' +
            '<td style="padding:10px;color:var(--text-muted);">' + c.sas + '</td>' +
            '</tr>';
    }).join('');

    el.innerHTML =
        '<table style="width:100%;border-collapse:collapse;text-align:left;font-size:0.88rem;">' +
            '<thead><tr style="background:rgba(255,199,44,0.15);color:var(--gold-primary);' +
            'border-bottom:1px solid rgba(255,255,255,0.2);">' +
                '<th style="padding:12px;">Column Name</th>' +
                '<th style="padding:12px;">Data Type</th>' +
                '<th style="padding:12px;">Allowed Values &amp; Meaning</th>' +
                '<th style="padding:12px;">SAS vs Python Note</th>' +
            '</tr></thead>' +
            '<tbody>' + rows + '</tbody>' +
        '</table>';
}
